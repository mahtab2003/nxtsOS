/* Host test for web/SSL Phase 3 crypto: MD5 (RFC 1321), SHA-1
   (FIPS 180-1), AES-128/256 decrypt (FIPS 197). Follows the
   host_pss.c pattern: compiles the kernel C files on the host
   with shims. Build:
   gcc -fno-builtin -o /tmp/host_legacy tests/host_legacy_crypto.c kernel/md5.c kernel/sha1.c kernel/sha256.c kernel/aes.c net/bignum.c net/rsaverify.c
   (run from ~/workspace/nxtsOS). Exit 0 on PASS. The final
   lines print MD5/SHA-1 of a 1000-byte pattern for a Python
   hashlib cross-check (the fixed vectors above are the
   primary proof; the cross-check guards against a shared
   misunderstanding of the vector encodings). */
