void *memset(void *dst, int val, u32 n) {
    u8 *d = dst;
    for (u32 i = 0; i < n; i++) d[i] = (u8)val;
    return dst;
}
void *memcpy(void *dst, const void *src, u32 n) {
    const u8 *s = src;
    u8 *d = dst;
    for (u32 i = 0; i < n; i++) d[i] = s[i];
    return dst;
}
int memcmp(const void *a, const void *b, u32 n) {
    const u8 *x = a, *y = b;
    for (u32 i = 0; i < n; i++) if (x[i] != y[i]) return x[i] < y[i] ? -1 : 1;
    return 0;
}
u32 strlen(const char *s) { u32 n = 0; while (s[n]) n++; return n; }

static int fails = 0;

static void hexout(const u8 *p, u32 n) {
    for (u32 i = 0; i < n; i++) printf("%02x", p[i]);
}

static void check_hex(const char *name, const u8 *got, const char *want_hex, u32 n) {
    char got_hex[129];
    for (u32 i = 0; i < n; i++) {
        got_hex[i * 2] = "0123456789abcdef"[got[i] >> 4];
        got_hex[i * 2 + 1] = "0123456789abcdef"[got[i] & 15];
    }
    got_hex[n * 2] = 0;
    if (strcmp(got_hex, want_hex) != 0) {
        printf("FAIL %s: got %s want %s\n", name, got_hex, want_hex);
        fails++;
    } else {
        printf("ok %s\n", name);
    }
}

/* (strcmp is defined above check_hex.) */
