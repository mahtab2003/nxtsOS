/* AP trampoline (redesign 4, CORE_CLI.md section 15.3).
   The BSP copies this blob to 0x8000 and starts an AP with a SIPI
   (vector 0x08). The AP enters in real mode with CS = 0x0800, IP = 0.
 *
   Linked at 0 (see scripts/build.sh), so every label value is an
   OFFSET from the blob start, not a linear address. That is what
   makes the two far jumps work:
     - real mode: DS is set to CS (0x0800), so a label offset O
       addresses linear 0x8000 + O. The temporary GDT below has
       base 0x8000 for both segments, so after CR0.PE the first
       far jump (16-bit offset O) lands at linear 0x8000 + O.
     - protected mode, temp segments: DS still has base 0x8000,
       so slot reads (lgdt/lidt/mov) address the blob correctly.
     - after the second far jump (32-bit offset 0x8000 + O, new
       CS base 0), DS/SS still have base 0x8000 until they are
       reloaded — so the slots MUST be read into registers
       before DS is reloaded, which is the order below.
   The BSP patches the five slots (see kernel/tramp_offsets.h,
   generated by tools/gentramp.py from nm output — never hardcode
   their offsets in C). The trampoline never touches the stack
   before ESP is set in pm_entry2, and never uses any kernel
   symbol directly: everything it needs arrives in a slot. */
.section .text
.code16
.global tramp_start
tramp_start:
    cli
    mov %cs, %ax
    mov %ax, %ds
    lgdt tramp_gdt_ptr
    mov %cr0, %eax
    or $0x00000001, %eax
    mov %eax, %cr0
    ljmp $0x08, $pm_entry

/* Temporary GDT (base 0x8000, 4 GiB limit, 32-bit segments):
   0x08 code, 0x10 data. Only the trampoline uses it; the AP
   loads the real GDT in pm_entry. */
tramp_gdt:
    .quad 0
    .word 0xFFFF, 0x8000
    .byte 0x00, 0x9A, 0xCF, 0x00
    .word 0xFFFF, 0x8000
    .byte 0x00, 0x92, 0xCF, 0x00
tramp_gdt_end:
tramp_gdt_ptr:
    .word tramp_gdt_end - tramp_gdt - 1
    .long 0x8000 + tramp_gdt

.code32
pm_entry:
    mov $0x10, %ax
    mov %ax, %ds
    mov %ax, %es
    mov %ax, %fs
    mov %ax, %gs
    mov %ax, %ss
    /* Load the real GDT (slot: limit + base, written by the BSP),
       then reload CS from it. The jump target is the ABSOLUTE
       linear address: CS will have base 0 after this jump. */
    lgdt tramp_slot_gdt
    ljmp $0x08, $(0x8000 + pm_entry2)

pm_entry2:
    /* DS/SS still have base 0x8000 here, so slot reads work.
       Read everything into registers BEFORE reloading DS. */
    lidt tramp_slot_idt
    mov tramp_slot_stack, %esp
    mov tramp_slot_entry, %eax
    mov tramp_slot_pd, %ecx
    mov %ecx, %cr3
    mov %cr0, %ecx
    and $0x9FFFFFFF, %ecx   /* clear CD/NW left set by reset */
    or $0x80000001, %ecx    /* PE + PG, matching the BSP */
    mov %ecx, %cr0
    /* Paging is on (identity map covers the blob and the stack).
       Now reload the data segments from the real GDT. */
    mov $0x10, %dx
    mov %dx, %ds
    mov %dx, %es
    mov %dx, %fs
    mov %dx, %gs
    mov %dx, %ss
    call *%eax              /* ap_main(): never returns */
    cli
1:  hlt
    jmp 1b

/* BSP-patched slots (offsets generated into tramp_offsets.h). */
.global tramp_slot_gdt
.global tramp_slot_idt
.global tramp_slot_stack
.global tramp_slot_pd
.global tramp_slot_entry
tramp_slot_gdt:
    .word 0
    .long 0
tramp_slot_idt:
    .word 0
    .long 0
tramp_slot_stack:
    .long 0
tramp_slot_pd:
    .long 0
tramp_slot_entry:
    .long 0
.section .note.GNU-stack,"",@progbits
