#!/usr/bin/env python3
"""Generate kernel/font_data.h from a host console font (PSF).
Usage: python3 tools/genfont.py [input.psf.gz] [output.h]
Default input: /usr/share/consolefonts/Lat15-VGA16.psf.gz (8x16, 256 glyphs).
The generated file is a bitmap font, not nxtsOS original code: it is
the host's standard VGA console font, embedded so the kernel can
render text in graphics mode without a BIOS font. Regenerate it if
you want a different font; the kernel only uses glyph rows as bytes,
MSB = leftmost pixel, 16 rows per glyph.
PSF1: magic 0x36 0x04, mode byte, charsize byte, then glyphs.
PSF2: magic 0x72 0xb5 0x4a 0x86, version, headersize, flags,
      glyph count, glyph size, height, width, then glyphs.
"""
import gzip, struct, sys

def load_psf(path):
    raw = gzip.open(path, "rb").read() if path.endswith(".gz") else open(path, "rb").read()
    if raw[:2] == b"\x36\x04":
        mode, charsize = raw[2], raw[3]
        count = 512 if mode & 1 else 256
        glyphs = [raw[4 + i*charsize: 4 + (i+1)*charsize] for i in range(count)]
        height = charsize
        width = 8
        return glyphs, width, height
    if raw[:4] == b"\x72\xb5\x4a\x86":
        ver, hdrsize, flags, count, glyphsize, height, width = struct.unpack("<IIIIIII", raw[4:32])
        glyphs = [raw[hdrsize + i*glyphsize: hdrsize + (i+1)*glyphsize] for i in range(count)]
        return glyphs, width, height
    raise SystemExit(f"genfont: unrecognised PSF format in {path}")

def main():
    inp = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-VGA16.psf.gz"
    out = sys.argv[2] if len(sys.argv) > 2 else "kernel/font_data.h"
    glyphs, width, height = load_psf(inp)
    if width != 8 or height != 16:
        raise SystemExit(f"genfont: expected 8x16 font, got {width}x{height} from {inp}")
    if len(glyphs) < 128:
        raise SystemExit(f"genfont: only {len(glyphs)} glyphs, need at least 128")
    # Use the first 256 glyphs (or fewer, padded with blanks).
    glyphs = glyphs[:256]
    while len(glyphs) < 256:
        glyphs.append(b"\x00" * 16)
    with open(out, "w") as f:
        f.write("/* Generated by tools/genfont.py from %s.\n" % inp)
        f.write("   8x16 bitmap font, 256 glyphs, MSB = leftmost pixel.\n")
        f.write("   This is a standard console font, not nxtsOS original code. */\n")
        f.write("#ifndef NXTS_FONT_DATA_H\n#define NXTS_FONT_DATA_H\n")
        f.write("#include \"common.h\"\n")
        f.write("static const u8 font8x16[256][16] = {\n")
        for g in glyphs:
            f.write("    {" + ",".join(f"0x{b:02x}" for b in g) + "},\n")
        f.write("};\n#endif\n")
    print(f"genfont: wrote {out} from {inp} (256 glyphs, 8x16)")

if __name__ == "__main__":
    main()
