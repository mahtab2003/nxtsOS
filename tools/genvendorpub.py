#!/usr/bin/env python3
"""Generate kernel/vendor_pubkey.h from the vendor RSA private key.

Usage: python3 tools/genvendorpub.py build/signing.key kernel/vendor_pubkey.h

The kernel embeds ONLY the public modulus (RSA-2048, exponent fixed
at 65537). The private key never enters the kernel tree, the source
archive, or the distribution zip — build.sh keeps it in build/
(which is git-ignored and excluded from archives). If the key is
lost, regenerate it and rebuild: the kernel and every signed
package must use the same keypair.

Fails loudly if the key is not RSA-2048 or its exponent is not
65537, so a wrong key can never silently produce a kernel that
refuses every signed package.
"""
import re, subprocess, sys

def fail(msg):
    sys.exit(f"genvendorpub: {msg}")

def main():
    if len(sys.argv) != 3:
        fail("usage: genvendorpub.py <private-key.pem> <output.h>")
    key, out = sys.argv[1], sys.argv[2]
    r = subprocess.run(["openssl", "rsa", "-in", key, "-modulus", "-noout"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        fail(f"openssl -modulus failed: {r.stderr.strip()}")
    m = re.search(r"Modulus=([0-9A-Fa-f]+)", r.stdout)
    if not m or len(m.group(1)) != 512:
        fail(f"expected a 512-hex-char (2048-bit) modulus, got {len(m.group(1)) if m else 0} chars")
    mod = bytes.fromhex(m.group(1))
    r = subprocess.run(["openssl", "rsa", "-in", key, "-text", "-noout"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        fail(f"openssl -text failed: {r.stderr.strip()}")
    em = re.search(r"publicExponent:\s*(\d+)", r.stdout)
    if not em or int(em.group(1)) != 65537:
        fail(f"expected public exponent 65537, got {em.group(1) if em else 'none'}")
    body = ",\n    ".join(
        ", ".join(f"0x{b:02X}" for b in mod[i:i + 12])
        for i in range(0, len(mod), 12))
    with open(out, "w") as f:
        f.write("/* GENERATED by tools/genvendorpub.py at build time — do not edit.\n"
                "   Vendor RSA-2048 public key (exponent 65537) for package\n"
                "   signature verification. Regenerated on every build from\n"
                "   build/signing.key, so it can never drift from the key\n"
                "   that signed the distribution packages. */\n"
                "#ifndef NXTS_VENDOR_PUBKEY_H\n"
                "#define NXTS_VENDOR_PUBKEY_H\n"
                "#include \"common.h\"\n"
                "static const u8 VENDOR_MOD[256] = {\n    " + body + "\n};\n"
                "#define VENDOR_EXP 65537u\n"
                "#endif\n")
    print(f"Wrote {out}: vendor RSA-2048 public key (exponent 65537)")

if __name__ == "__main__":
    main()
