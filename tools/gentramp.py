#!/usr/bin/env python3
"""Generate kernel/tramp_offsets.h from the AP trampoline ELF.
The trampoline is linked at 0, so nm symbol values ARE the blob
offsets the BSP must patch (see boot/trampoline.S). Fails the
build if the blob does not fit in one page (0x8000 must not
collide with anything else in low memory) or a slot is missing.
Usage: python3 tools/gentramp.py <trampoline.elf> <trampoline.bin> <out.h>
"""
import subprocess
import sys

ELF, BIN, OUT = sys.argv[1:4]
SLOTS = ["tramp_slot_gdt", "tramp_slot_idt", "tramp_slot_stack",
         "tramp_slot_pd", "tramp_slot_entry"]

out = subprocess.run(["nm", ELF], capture_output=True, text=True)
if out.returncode != 0:
    print(out.stdout, out.stderr)
    raise SystemExit(1)
syms = {}
for line in out.stdout.splitlines():
    parts = line.split()
    if len(parts) == 3:
        syms[parts[2]] = int(parts[0], 16)

import os
size = os.path.getsize(BIN)
if size >= 4096:
    print(f"trampoline blob too large: {size} bytes (must fit one page)")
    raise SystemExit(1)
missing = [s for s in SLOTS if s not in syms]
if missing:
    print("trampoline slots missing from nm output:", missing)
    raise SystemExit(1)

with open(OUT, "w") as f:
    f.write("/* Generated by tools/gentramp.py — do not edit.\n")
    f.write("   Blob offsets (trampoline linked at 0) patched by the\n")
    f.write("   BSP before the SIPI sequence. See boot/trampoline.S. */\n")
    for s in SLOTS:
        macro = "TRAMP_SLOT_" + s[len("tramp_slot_"):].upper()
        f.write(f"#define {macro} 0x{syms[s]:x}u\n")
    f.write(f"#define TRAMP_BLOB_SIZE {size}u\n")
print(f"trampoline offsets written to {OUT} ({size} bytes)")
