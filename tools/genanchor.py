#!/usr/bin/env python3
"""Generate net/tls_anchor.h from a PEM certificate.

Usage: python3 tools/genanchor.py <cert.pem> <output.h>

The kernel embeds ONLY the public modulus (RSA-2048, exponent fixed
at 65537) of the issuing certificate that anchors a TLS chain — the
pinned intermediate (currently Google Trust Services WR1, which
issues *.vercel.app). The private key is never involved: this tool
reads a public certificate, so the output header is public data and
is committed to the tree (unlike vendor_pubkey.h, which is
regenerated every build from a private key).

Fails loudly if the certificate is not RSA-2048 or its exponent is
not 65537, so a wrong anchor can never silently produce a kernel
that refuses every anchored handshake. When the anchor rotates
(Google rotates intermediates rarely), re-run this tool with the
new certificate and rebuild: anchored handshakes fail closed
(refused) until the kernel carries the new anchor.
"""
import re, subprocess, sys

def fail(msg):
    sys.exit(f"genanchor: {msg}")

def main():
    if len(sys.argv) != 3:
        fail("usage: genanchor.py <cert.pem> <output.h>")
    cert, out = sys.argv[1], sys.argv[2]
    r = subprocess.run(["openssl", "x509", "-in", cert, "-modulus", "-noout"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        fail(f"openssl -modulus failed: {r.stderr.strip()}")
    m = re.search(r"Modulus=([0-9A-Fa-f]+)", r.stdout)
    if not m or len(m.group(1)) != 512:
        fail(f"expected a 512-hex-char (2048-bit) modulus, got {len(m.group(1)) if m else 0} chars")
    mod = bytes.fromhex(m.group(1))
    r = subprocess.run(["openssl", "x509", "-in", cert, "-text", "-noout"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        fail(f"openssl -text failed: {r.stderr.strip()}")
    em = re.search(r"Exponent:\s*(\d+)", r.stdout)
    if not em or int(em.group(1)) != 65537:
        fail(f"expected public exponent 65537, got {em.group(1) if em else 'none'}")
    subj = subprocess.run(["openssl", "x509", "-in", cert, "-subject", "-noout"],
                          capture_output=True, text=True).stdout.strip()
    body = ",\n    ".join(
        ", ".join(f"0x{b:02X}" for b in mod[i:i + 12])
        for i in range(0, len(mod), 12))
    with open(out, "w") as f:
        f.write("/* GENERATED by tools/genanchor.py — do not edit by hand.\n"
                "   Pinned TLS trust anchor: the RSA-2048 public key\n"
                "   (exponent 65537) of the issuing certificate below.\n"
                "   An anchored handshake accepts a chain only when its\n"
                "   terminal certificate's key equals this anchor (or a\n"
                "   modulus listed in root-owned tlsanchors.txt).\n"
                "   This header is PUBLIC data (a certificate's public\n"
                "   key) and is committed to the tree. Re-run\n"
                "   genanchor.py with the new certificate when the\n"
                "   anchor rotates. */\n"
                f"/* Anchor certificate subject: {subj} */\n"
                "#ifndef NXTS_TLS_ANCHOR_H\n"
                "#define NXTS_TLS_ANCHOR_H\n"
                "#include \"../kernel/common.h\"\n"
                "static const u8 TLS_ANCHOR_MOD[256] = {\n    " + body + "\n};\n"
                "#define TLS_ANCHOR_EXP 65537u\n"
                "#endif\n")
    print(f"Wrote {out}: TLS anchor (RSA-2048, exponent 65537)")

if __name__ == "__main__":
    main()
